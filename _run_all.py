#!/usr/bin/env python3
"""One-shot runner: install deps, inspect data, run tests, build the feature
store, run the version comparison and lineage generation, and save all output
to outputs/artifacts/ for submission. Run from the repo root:
    python _run_all.py
"""
import subprocess
import sys
from pathlib import Path

ART = Path("outputs/artifacts")
ART.mkdir(parents=True, exist_ok=True)

# Use the project venv python so subprocesses have pandas/numpy/pyarrow/pytest.
# _run_all.py is at <repo>/assignment/starter-code/_run_all.py; .venv is at <repo>/.venv.
_VENV_PY = str(Path(__file__).resolve().parents[2] / ".venv" / "Scripts" / "python.exe")
PY = _VENV_PY if Path(_VENV_PY).exists() else "python"


def run(cmd, label, out_file=None):
    # Replace a leading "python " with the venv python so subprocesses resolve
    # dependencies from the venv, not the system python.
    if cmd.startswith("python "):
        cmd = f'"{PY}" ' + cmd[len("python "):]
    print("\n" + "=" * 70)
    print(f"=== {label}")
    print("=" * 70)
    result = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    text = result.stdout + ("\n--- STDERR ---\n" + result.stderr if result.stderr else "")
    print(text)
    if out_file:
        (ART / out_file).write_text(
            f"$ {cmd}\n\n{text}\n[exit {result.returncode}]\n", encoding="utf-8"
        )
    return result.returncode


def main():
    # 1. Inspect data -> save full inspection output
    run("python _inspect_data.py", "DATA INSPECTION", "data_inspection_output.txt")

    # 2. Run the test suite, verbose -> save
    rc = run("python -m pytest -v", "TEST SUITE", "pytest_output.txt")

    # 3. Build training features + populate the feature store
    run("python scripts/build_training_features.py --as-of 2026-08-01",
        "BUILD TRAINING FEATURES", "build_output.txt")

    # 4. Version comparison
    run("python scripts/compare_feature_versions.py",
        "VERSION COMPARISON", "version_comparison_output.txt")

    # 5. Lineage (also generated by the build, but re-run to capture)
    run("python scripts/generate_lineage.py",
        "LINEAGE GENERATION", "lineage_output.txt")

    # 6. Scoring example
    run("python scripts/score_customer.py --customer-id 1 --customer-id 50 --as-of 2026-08-01",
        "SCORING EXAMPLE", "scoring_output.txt")

    # 7. Feature-store registry query (spot-check evidence)
    run("python _registry_query.py",
        "FEATURE STORE REGISTRY QUERY", "feature_store_registry_query.txt")

    # 8. Parity mutation check (writes PARITY_CHECK.md)
    run("python _parity_mutation.py",
        "PARITY MUTATION CHECK", "parity_mutation_run.txt")

    print("\n" + "=" * 70)
    print("ALL DONE — see outputs/artifacts/ for saved results.")
    print("=" * 70)
    return rc


if __name__ == "__main__":
    sys.exit(main())
